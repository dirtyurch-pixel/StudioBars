  await page.getByText(/WordNet does not have “zorblax”/).waitFor({ timeout: 6000 })
  check('an unknown word is reported honestly, with no invented meanings', (await page.getByRole('article').count()) === 0)

  // typing does not hammer the server or flicker
  await typeWord('rain')
  await page.getByRole('article').first().waitFor()
  await line(page, 1).click()
  await page.getByRole('article').first().waitFor()
  meaningCalls = 0
  await line(page, 1).fill('')
  await line(page, 1).pressSequentially('rain keeps tapping on the window glass tonight', { delay: 20 })

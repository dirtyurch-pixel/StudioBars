  const said = await page.getByRole('note').allInnerTexts()
  check('"lead" shows both ways of saying it, per meaning (led / leed)', said.some((t) => /lˈɛd/.test(t)) && said.some((t) => /lˈid/.test(t)), JSON.stringify(said.slice(0, 4)))


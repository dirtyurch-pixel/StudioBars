  check('still nothing sent while it is off, even after looking a word up', (await fakeLog()).length === 0)
  await box.click()
  await page.waitForFunction(() => document.querySelector('.online-switch input[type=checkbox]').checked, null, { timeout: 5000 })
  const res = page.getByLabel('Online results')
  await res.waitFor({ timeout: 8000 })
  check('after switching on, results are labelled as live from the internet', /Online · live from Datamuse/.test(await res.innerText()))
  check('results appear', (await res.locator('.chip-online').allInnerTexts()).includes('storm'))
  check('and it says only the one word was sent', /Only the word “rain” was sent/.test(await res.innerText()))
  let lg = await fakeLog()
  check('exactly ONE request left, containing only the word', lg.length === 1 && /^\/words\?ml=rain&max=30$/.test(lg[0].path), JSON.stringify(lg))
  check('the request carried no cookies or credentials', !lg[0].headers.some((h) => ['cookie', 'authorization', 'x-api-key'].includes(h)), lg[0].headers.join())
  await page.getByRole('button', { name: 'Often used with' }).click()
  await page.getByLabel('Online results').getByText('umbrella').waitFor({ timeout: 8000 })
  await page.getByRole('button', { name: 'Related words' }).click()
  await page.getByLabel('Online results').getByText('storm').waitFor({ timeout: 8000 })
  lg = await fakeLog()
  check('going back to an earlier question uses the saved answer (no new request)', lg.length === 2, `${lg.length} requests`)
  check('the saved answer is labelled as a saved copy', /Saved copy/.test(await page.getByLabel('Online results').innerText()))

  // online rhymes from the Rhymes tab
  await openTool(page, 'Rhymes')
  await page.getByLabel('Word to look up').fill('fade')
  await page.getByRole('button', { name: 'Look up' }).click()
  await page.getByRole('region', { name: /syllable/ }).first().waitFor({ timeout: 8000 })
  await page.getByText(/Online rhymes \(optional\)/).click()
  await page.getByLabel('Online results').getByText('afraid').waitFor({ timeout: 8000 })
  check('online rhymes work from the Rhymes tab too, and say they are online', /Online/.test(await page.getByLabel('Online results').innerText()))


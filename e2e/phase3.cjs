  await page.getByRole('article').first().waitFor()
  check('a word with many meanings folds the list and offers "Show all"', (await page.getByRole('button', { name: /^Show all \d+ meanings$/ }).count()) === 1)
  check('synonyms that usually mean something else carry a warning marker', (await page.getByLabel('meaning may change').count()) >= 1)
  const warnTitle = await page.locator('.chip-word.shifty').first().getAttribute('title')
  check('the warning says what the word usually means instead', /usually means/.test(warnTitle || ''), warnTitle)
  check('every meaning has its own synonym row (not one blended list)', (await page.getByRole('article').count()) >= 3)

  await typeWord('lead')
  await page.getByRole('article').first().waitFor()

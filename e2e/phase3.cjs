  watch(page)
  const errors = []
  const hosts = new Set()
  let meaningCalls = 0
  page.on('pageerror', (e) => errors.push(String(e)))
  page.on('request', (r) => {
    try { const u = new URL(r.url()); if (/^https?:$/.test(u.protocol)) hosts.add(u.hostname); if (u.pathname === '/api/lexicon/word') meaningCalls++ } catch {}
  })
  await fake('/__reset'); await fake('/__mode?m=ok')

  await page.goto(APP)
  await page.getByRole('button', { name: '+ New song' }).first().click()
  await page.getByLabel('Title').fill('Words Test')
  await page.getByRole('button', { name: 'Create song' }).click()

  const wordsNow = () => page.locator('.rhyme-panel .chip-word').allInnerTexts().then((a) => a.map((x) => x.replace(/(Near|mine|Same vowels|Same ending).*$/, '').trim()))
  await page.getByLabel('Word familiarity').selectOption('any')
  await page.getByLabel('Part of speech').selectOption('noun')
  await page.getByText(/usually used as a noun/).waitFor({ timeout: 8000 })
  const nouns = await wordsNow()
  check('"Usually a noun" keeps nouns (grade, blade) and drops verbs (made)', nouns.includes('grade') && nouns.includes('blade') && !nouns.includes('made'), JSON.stringify(nouns.slice(0, 15)))
  await page.getByLabel('Part of speech').selectOption('verb')
  await page.getByText(/usually used as a verb/).waitFor({ timeout: 8000 })

  check('search finds a phrase by a word in its meaning', /come up/.test(await page.locator('.phrase-list').innerText()))
  await page.getByLabel('Search your phrases').fill('')
  await page.getByRole('button', { name: /^slang \(1\)/ }).click()
  await page.waitForFunction(() => document.querySelectorAll('.phrase-list > li').length === 1 && /finna/.test(document.querySelector('.phrase-list').innerText), null, { timeout: 5000 })
  check('filtering by tag works', /finna/.test(await page.locator('.phrase-list').innerText()))
  await page.getByRole('button', { name: 'All', exact: true }).click()
  await page.reload()
  await line(page, 1).waitFor()
  await openTool(page, 'Words')
  await page.getByRole('tab', { name: 'My phrases' }).click()
  await page.getByText('on the come up').waitFor({ timeout: 6000 })
  check('phrases are still there after reloading the page', (await page.locator('.phrase-list > li').count()) === 2)

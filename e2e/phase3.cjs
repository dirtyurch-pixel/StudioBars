  check('the whole bank can be exported as a file (and holds nothing private)', exported.format === 'studio-bars-phrases' && exported.phrases.length === 2 && Object.keys(exported.phrases[0]).sort().join() === 'meaning,phrase,sounds_like,tags', JSON.stringify(exported).slice(0, 200))
  await page.locator('.phrase-list > li', { hasText: 'on the come up' }).getByRole('button', { name: 'Rhymes' }).click()
  await page.getByRole('note').filter({ hasText: /Experimental/ }).waitFor({ timeout: 8000 })
  check('"Rhymes" on a phrase opens the experimental phrase search for it', (await page.getByLabel('Phrase', { exact: true }).inputValue()) === 'on the come up')
  await openTool(page, 'Words')
  await page.getByRole('tab', { name: 'My phrases' }).click()
  await page.locator('.phrase-list > li', { hasText: 'on the come up' }).getByLabel('Delete on the come up').click()
  await page.getByRole('button', { name: 'Yes', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.phrase-list > li').length === 1, null, { timeout: 5000 })
  check('deleting asks first, then removes the phrase', true)

  // ---------------------------------------------------------------- the online helper
  check('nothing has been sent to the online service so far (it is off by default)', (await fakeLog()).length === 0)
  await page.getByRole('tab', { name: 'Online ideas' }).click()
  const box = page.getByRole('checkbox', { name: /Use the online word helper/ })
  check('the online helper is OFF by default', !(await box.isChecked()))
  check('it says exactly what is sent and to whom', (await page.getByText(/Only the single word you look up/).isVisible()) && (await page.getByText(/127\.0\.0\.1:8765|api\.datamuse\.com/).first().isVisible()))
  check('it warns that Datamuse will need an API key from 1 February 2027', await page.getByText(/API key will be required from 1 February 2027/).isVisible())
  await page.getByLabel('Word to look up').fill('rain')
  await page.getByRole('button', { name: 'Look up' }).click()

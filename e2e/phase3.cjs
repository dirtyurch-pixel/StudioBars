  check('phrase rhymes are clearly labelled experimental', await page.getByRole('note').filter({ hasText: /Experimental/ }).isVisible())
  await page.getByLabel('Phrase', { exact: true }).fill('pay attention')
  await page.getByRole('button', { name: 'Find rhymes' }).click()
  await page.getByRole('region', { name: 'Phrase rhymes' }).waitFor({ timeout: 8000 })
  const pr = await page.getByRole('region', { name: 'Phrase rhymes' }).locator('.chip-word').allInnerTexts()
  check('"pay attention" finds multi-syllable rhymes (tension, mention)', pr.some((t) => t.startsWith('tension')) && pr.some((t) => t.startsWith('mention')), JSON.stringify(pr.slice(0, 10)))
  check('words already in the phrase are not offered back', !pr.some((t) => t.startsWith('attention')))
  await page.getByLabel('Syllables to match').selectOption('1')
  await page.waitForFunction(() => /last 1 syllable/.test(document.querySelector('[aria-label="Phrase rhymes"]')?.innerText || ''), null, { timeout: 8000 })
  check('changing the number of syllables changes the match', true)
  await page.getByLabel('Phrase', { exact: true }).fill('zorblax fade')
  await page.getByRole('button', { name: 'Find rhymes' }).click()
  await page.getByRole('alert').filter({ hasText: /zorblax/ }).waitFor({ timeout: 8000 })
  check('a phrase with an unknown word says which word to teach first', true)
  await page.getByRole('tab', { name: 'One word' }).click()

  // ---------------------------------------------------------------- phrase bank
  await openTool(page, 'Words')
  await page.getByRole('tab', { name: 'My phrases' }).click()
  await page.getByText(/Nothing here yet/).waitFor()

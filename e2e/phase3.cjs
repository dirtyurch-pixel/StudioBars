  await fake('/__mode?m=down')
  await openTool(page, 'Words')
  await page.getByRole('tab', { name: 'Online ideas' }).click()
  await page.getByLabel('Word to look up').fill('thunder')
  await page.getByRole('button', { name: 'Look up' }).click()
  await page.getByRole('alert').filter({ hasText: /Nothing saved for this word yet/ }).waitFor({ timeout: 10000 })
  check('when the service is unreachable and nothing is saved, a clear message appears (no freeze)', true)
  await page.getByLabel('Word to look up').fill('rain')
  await page.getByRole('button', { name: 'Look up' }).click()
  await page.getByLabel('Online results').waitFor({ timeout: 8000 })
  check('a word already saved still works while the service is down', (await page.getByLabel('Online results').locator('.chip-online').count()) > 0)
  await line(page, 1).fill('typing continues while the online service is down')
  check('writing is completely unaffected by the outage', (await line(page, 1).inputValue()) === 'typing continues while the online service is down')
  await sleep(1500) // let the app's own safety rate limit recover after the burst of lookups above
  await fake('/__mode?m=refuse')
  await page.getByLabel('Word to look up').fill('thunder')
  await page.getByRole('button', { name: 'Look up' }).click()
  await page.getByRole('alert').filter({ hasText: /may now need an API key/ }).waitFor({ timeout: 10000 })

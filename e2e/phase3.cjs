  await page.getByText('about to; fixing to').waitFor()
  await addPhrase('on the come up', 'rising fast in the game', '', 'hustle')
  await page.getByText('rising fast in the game').waitFor()
  const bank = await page.locator('.phrase-list').innerText()
  check('phrases show meaning, syllable count and how they sound', /finna/.test(bank) && /2 syllables/.test(bank) && /sounds like “finer”/.test(bank), bank.slice(0, 250))
  check('tags are tidied to lower case', /#slang/.test(bank) && /#south/.test(bank))
  await addPhrase('FINNA', 'again', '', '')
  await page.getByRole('alert').filter({ hasText: /already in your phrase bank/ }).waitFor()
  check('a duplicate is refused with a clear reason (and what was typed is kept)', (await page.getByLabel('Phrase or slang word').inputValue()) === 'FINNA')
  await page.getByRole('button', { name: 'Cancel' }).click()
